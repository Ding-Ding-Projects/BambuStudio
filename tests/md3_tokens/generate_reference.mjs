// Regenerates md3_dynamic_color_reference.inc from Google's
// material-color-utilities, the reference implementation that
// src/slic3r/GUI/Widgets/MD3DynamicColor.cpp is ported from.
//
// The library ships extensionless ES module imports, so it is bundled first:
//
//   mkdir /tmp/mcu && cd /tmp/mcu && npm init -y
//   npm install @material/material-color-utilities@0.4.0 esbuild
//   cp <repo>/tests/md3_tokens/generate_reference.mjs .
//   npx esbuild generate_reference.mjs --bundle --platform=node --format=esm --outfile=gen.mjs
//   node gen.mjs > <repo>/tests/md3_tokens/md3_dynamic_color_reference.inc
import {
  Hct, SchemeTonalSpot, MaterialDynamicColors, argbFromHex, hexFromArgb,
} from '@material/material-color-utilities';

const ROLES = [
  'primary', 'onPrimary', 'primaryContainer', 'onPrimaryContainer', 'inversePrimary',
  'secondary', 'onSecondary', 'secondaryContainer', 'onSecondaryContainer',
  'tertiary', 'onTertiary', 'tertiaryContainer', 'onTertiaryContainer',
  'error', 'onError', 'errorContainer', 'onErrorContainer',
  'background', 'onBackground', 'surface', 'surfaceDim', 'surfaceBright',
  'surfaceContainerLowest', 'surfaceContainerLow', 'surfaceContainer',
  'surfaceContainerHigh', 'surfaceContainerHighest', 'onSurface',
  'surfaceVariant', 'onSurfaceVariant', 'inverseSurface', 'inverseOnSurface',
  'outline', 'outlineVariant', 'shadow', 'scrim', 'surfaceTint',
  'primaryFixed', 'primaryFixedDim', 'onPrimaryFixed', 'onPrimaryFixedVariant',
  'secondaryFixed', 'secondaryFixedDim', 'onSecondaryFixed', 'onSecondaryFixedVariant',
  'tertiaryFixed', 'tertiaryFixedDim', 'onTertiaryFixed', 'onTertiaryFixedVariant',
];

// The app's approved seeds, the prototype's accent swatches, the sRGB corners
// and a deterministic spread of other colours.
const named = [
  '#146c2e', '#7c5cff', '#14b8a6', '#22c55e', '#3b82f6', '#f97316', '#ec4899',
  '#000000', '#ffffff', '#808080', '#ff0000', '#00ff00', '#0000ff', '#ffff00',
  '#00ffff', '#ff00ff', '#6750a4', '#b3261e', '#f5c518', '#111418',
];
const seeds = [...named];
let state = 0x2545f491;
const next = () => { state ^= state << 13; state >>>= 0; state ^= state >>> 17; state ^= state << 5; state >>>= 0; return state; };
while (seeds.length < 120) seeds.push('#' + (next() & 0xffffff).toString(16).padStart(6, '0'));

const mdc = new MaterialDynamicColors();
const hex = (argb) => '0x' + (argb >>> 0).toString(16).toUpperCase().padStart(8, '0') + 'u';
const round = (v) => Math.round(v * 1e6) / 1e6;

const schemes = [];
for (const seed of seeds) {
  for (const dark of [false, true]) {
    const scheme = new SchemeTonalSpot(Hct.fromInt(argbFromHex(seed)), dark, 0, '2021');
    const colors = {};
    for (const role of ROLES) colors[role] = hex(mdc[role]().getArgb(scheme));
    schemes.push({ seed, dark, colors });
  }
}

const hct = seeds.map((seed) => {
  const h = Hct.fromInt(argbFromHex(seed));
  return { seed, hue: round(h.hue), chroma: round(h.chroma), tone: round(h.tone) };
});

const solver = [];
for (let hue = 0; hue < 360; hue += 15) {
  for (const chroma of [0, 8, 24, 48, 84, 150]) {
    for (let tone = 0; tone <= 100; tone += 5) {
      solver.push({ hue, chroma, tone, argb: hex(Hct.from(hue, chroma, tone).toInt()) });
    }
  }
}

// Emitted as C++ so the test needs no JSON parser. Role order matches
// MD3::Dynamic::SchemeRole.
const out = [];
out.push('// Generated by tests/md3_tokens/generate_reference.mjs. Do not edit by hand.');
out.push('// Source: @material/material-color-utilities 0.4.0, SchemeTonalSpot, spec 2021, contrast 0.');
out.push(`static const char *const kRefRoleNames[${ROLES.length}] = { ${ROLES.map((r) => `"${r}"`).join(', ')} };`);
out.push('struct RefScheme { unsigned seed; bool dark; unsigned colors[' + ROLES.length + ']; };');
out.push('static const RefScheme kRefSchemes[] = {');
for (const s of schemes) out.push(`  { ${hex(argbFromHex(s.seed))}, ${s.dark}, { ${ROLES.map((r) => s.colors[r]).join(', ')} } },`);
out.push('};');
out.push('struct RefHct { unsigned seed; double hue, chroma, tone; };');
out.push('static const RefHct kRefHct[] = {');
for (const h of hct) out.push(`  { ${hex(argbFromHex(h.seed))}, ${h.hue}, ${h.chroma}, ${h.tone} },`);
out.push('};');
out.push('struct RefSolve { double hue, chroma, tone; unsigned argb; };');
out.push('static const RefSolve kRefSolve[] = {');
for (const s of solver) out.push(`  { ${s.hue}, ${s.chroma}, ${s.tone}, ${s.argb} },`);
out.push('};');
process.stdout.write(out.join('\n') + '\n');
