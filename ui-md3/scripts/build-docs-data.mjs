#!/usr/bin/env node
/*
 * Builds the documentation bundle the landing site reads in its Docs tab.
 *
 *   node ui-md3/scripts/build-docs-data.mjs <output.js> [wikiCheckout]
 *
 * Every English article under docs/features and its Cantonese twin
 * (<name>.yue_HK.md) become one record; the GitHub wiki, when a checkout is
 * given, is appended as its own area. The markdown is shipped as written and
 * rendered in the browser, so the site and the repository never disagree.
 *
 * The output is a classic script that sets window.BAMBU_DOCS, loaded on demand
 * when the Docs tab, the command palette or a feature card first needs it.
 */
import { readdir, readFile, writeFile, mkdir } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const scriptDir = path.dirname(fileURLToPath(import.meta.url));
const repoDir = path.resolve(scriptDir, '..', '..');
const docsDir = path.join(repoDir, 'docs', 'features');
const output = path.resolve(process.argv[2] || path.join(repoDir, '_site', 'site', 'docs.data.js'));
const wikiDir = process.argv[3] ? path.resolve(process.argv[3]) : '';
const REPO = 'https://github.com/Ding-Ding-Projects/BambuStudio';

const TWIN = /\.yue_HK\.md$/;

async function walk(directory, prefix, into) {
  for (const entry of (await readdir(directory, { withFileTypes: true })).sort((a, b) => a.name.localeCompare(b.name))) {
    const next = path.join(directory, entry.name);
    if (entry.isDirectory()) await walk(next, `${prefix}${entry.name}/`, into);
    else if (entry.name.endsWith('.md')) into.push(`${prefix}${entry.name}`);
  }
}

function stripFrontMatter(text) {
  const match = /^---\r?\n[\s\S]*?\r?\n---\r?\n/.exec(text);
  return match ? text.slice(match[0].length) : text;
}

function titleOf(markdown, fallback) {
  const match = /^#\s+(.+?)\s*$/m.exec(markdown);
  return match ? match[1].trim() : fallback;
}

function summaryOf(markdown) {
  const lines = markdown.replace(/\r\n/g, '\n').split('\n');
  let seenTitle = false;
  const collected = [];
  for (const line of lines) {
    if (!seenTitle) { if (/^#\s/.test(line)) seenTitle = true; continue; }
    const trimmed = line.trim();
    if (!trimmed) { if (collected.length) break; continue; }
    if (/^(#|\||```|<|-|\*|\d+\.|>)/.test(trimmed)) { if (collected.length) break; continue; }
    collected.push(trimmed);
    if (collected.join(' ').length > 220) break;
  }
  return collected.join(' ').replace(/[*_`]/g, '').replace(/\[([^\]]+)\]\([^)]*\)/g, '$1').slice(0, 240);
}

function idOf(relative) {
  return relative.replace(/\.md$/, '').replace(/[^A-Za-z0-9]+/g, '-').replace(/^-|-$/g, '').toLowerCase();
}

const files = [];
await walk(docsDir, '', files);
const twins = new Set(files.filter((f) => TWIN.test(f)));
const articles = [];
for (const relative of files) {
  if (TWIN.test(relative)) continue;
  const en = stripFrontMatter((await readFile(path.join(docsDir, relative), 'utf8')).replace(/\r\n/g, '\n'));
  const twinName = relative.replace(/\.md$/, '.yue_HK.md');
  const yue = twins.has(twinName)
    ? stripFrontMatter((await readFile(path.join(docsDir, twinName), 'utf8')).replace(/\r\n/g, '\n'))
    : '';
  const area = relative.includes('/') ? relative.split('/')[0] : 'general';
  articles.push({
    id: idOf(relative),
    area,
    path: `docs/features/${relative}`,
    source: `${REPO}/blob/master/docs/features/${relative}`,
    title: titleOf(en, relative),
    titleYue: yue ? titleOf(yue, '') : '',
    summary: summaryOf(en),
    summaryYue: yue ? summaryOf(yue) : '',
    en,
    yue
  });
}

const wiki = [];
if (wikiDir) {
  try {
    for (const name of (await readdir(wikiDir)).filter((n) => n.endsWith('.md')).sort()) {
      const text = (await readFile(path.join(wikiDir, name), 'utf8')).replace(/\r\n/g, '\n');
      wiki.push({
        id: 'wiki-' + idOf(name),
        area: 'wiki',
        path: `wiki/${name}`,
        source: `${REPO}/wiki/${name.replace(/\.md$/, '')}`,
        title: name.replace(/\.md$/, '').replace(/-/g, ' '),
        titleYue: '',
        summary: summaryOf(text),
        summaryYue: '',
        en: text,
        yue: ''
      });
    }
  } catch (error) {
    console.warn(`wiki checkout unreadable, continuing without it: ${error.message}`);
  }
}

const areas = {};
for (const article of articles.concat(wiki)) areas[article.area] = (areas[article.area] || 0) + 1;

const bundle = {
  generated: new Date().toISOString(),
  articleCount: articles.length,
  wikiCount: wiki.length,
  areas,
  articles: articles.concat(wiki)
};

await mkdir(path.dirname(output), { recursive: true });
await writeFile(output,
  '/* Generated by ui-md3/scripts/build-docs-data.mjs; do not edit. */\n' +
  'window.BAMBU_DOCS = ' + JSON.stringify(bundle) + ';\n');
console.log(`Wrote ${path.relative(process.cwd(), output)}: ${articles.length} articles, ${wiki.length} wiki pages`);
